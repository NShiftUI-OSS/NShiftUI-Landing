function domain(
  slug: string,
  title: string,
  lead: string,
  fields: string[],
  connects: string,
  notes?: string[],
): ReferenceEntry {
  return {
    path: `/ios/dominio/${slug}`,
    title,
    kicker: "Domínio iOS",
    lead,
    fields,
    connects,
    notes,
  }
}

