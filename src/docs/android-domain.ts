function domain(
  slug: string,
  title: string,
  lead: string,
  fields: string[],
  connects: string,
  notes?: string[],
): ReferenceEntry {
  return {
    path: `/android/dominio/${slug}`,
    title,
    kicker: "Domínio Android",
    lead,
    fields,
    connects,
    notes,
  }
}

